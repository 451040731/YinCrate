export function message (key, values = {}) {
  return { key, values };
}

export function translate (language, input, values = {}) {
  const english = normalizeLanguage(language) === "en";
  if (Array.isArray(input)) {
    return input.map((part) => translate(language, part)).join(english ? "; " : "；");
  }
  if (input && typeof input === "object") {
    return translate(language, input.key, input.values);
  }
  const key = String(input ?? "");
  const text = english && Object.hasOwn(ENGLISH, key) ? ENGLISH[key] : key;
  return text.replace(/\{(\w+)\}/g, (placeholder, name) => {
    if (!Object.hasOwn(values, name)) return placeholder;
    const value = values[name];
    return value && typeof value === "object"
      ? translate(language, value)
      : String(value);
  });
}
